#!/usr/bin/env node
/**
 * 岁时 (suishi) client build.
 *
 * The plugin ships as ONE plain-JavaScript client module loaded by the
 * Harness browser module loader. This script concatenates `src/parts/*.js`
 * (lexical order) into the loader wrapper and syntax-checks the result.
 * No bundler, no transpiler, no npm dependencies.
 *
 *   node build.mjs           # write client.js
 *   node build.mjs --check   # syntax-check only
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(fileURLToPath(import.meta.url))
const partsDir = path.join(root, 'src', 'parts')

const files = readdirSync(partsDir).filter((name) => name.endsWith('.js')).sort()
if (files.length === 0) throw new Error('no src/parts/*.js files found')

const chunks = files.map((name) => {
  const body = readFileSync(path.join(partsDir, name), 'utf8').replace(/\s+$/u, '')
  return `\n/* ============================== ${name} ============================== */\n${body}\n`
})

const HEADER = `/*
 * 岁时 (suishi) — DSH Web client half. GENERATED by build.mjs; edit src/parts/*.js instead.
 *
 * 中国年 · 全年节日倒计时：农历、二十四节气与自定义纪念日。
 * 农历/节气离线数据来自香港天文台 1901–2100 年公众日历（构建期生成，运行时不联网）。
 */
window.__ModuleLoader__.load({
\tid: '@local/dsh-suishi',
\tfactory(require) {
\t\tconst React = require('react')
\t\tconst h = React.createElement
\t\tconst Frag = React.Fragment
`

const FOOTER = `\t\treturn { inject, apply }
\t},
})
`

const code = HEADER + chunks.join('') + FOOTER

// Compile-only syntax check: never executes the body.
try {
  new Function('window', 'document', 'localStorage', 'navigator', 'require', code)
} catch (error) {
  console.error('syntax check failed:', error && error.message)
  process.exit(1)
}

if (process.argv.includes('--check')) {
  console.log(`OK ${files.length} parts, ${Buffer.byteLength(code)} bytes (syntax only)`)
  process.exit(0)
}

writeFileSync(path.join(root, 'client.js'), code)
console.log(`client.js written: ${files.length} parts, ${Buffer.byteLength(code)} bytes`)
